def transcribe(bars, tonic, end_units):
    semitones = [0, 2, 4, 5, 7, 9, 11]
    cursor, events, audit = 0, [], []
    for bar, text in enumerate(bars, 1):
        assert sum(int(t.split(":")[1]) for t in text.split()) == (end_units if bar == len(bars) else 16), bar
        offset = 0
        for token in text.split():
            pitch, units = token.split(":")
            units = int(units)
            degree = int(pitch[0])
            midi = tonic + semitones[degree - 1] - 12 * pitch.count("l") if degree else None
            hz = round(440 * 2 ** ((midi - 69) / 12)) if midi is not None else 0
            assert hz == 0 or 65 <= hz <= 4000
            events.append((cursor, hz, units))
            audit.append((bar, offset, pitch, units, hz))
            cursor += units
            offset += units
    return events, audit


def generate():
    assert len(QING_BARS) == 41 and len(FARU_BARS) == 23
    tracks = [("qinghuaci", QING_BARS, 60, 80, 12, gen_qinghuaci.transcribe()[1]),
              ("faruxue", FARU_BARS, 59, 58, 8, gen_faruxue.transcribe()[1])]
    lines = ["/* Generated by tools/gen_song_accompaniment.py from supplied lower staves.",
             " * One notated bass note per event; simultaneous chords keep lowest pitch. */"]
    preview, audit_rows = [], []
    for name, bars, tonic, bpm, ending, melody in tracks:
        events, audit = transcribe(bars, tonic, ending)
        assert sum(e[2] for e in events) == sum(e[2] for e in melody)
        lines.append(f"static const SongNote s_{name}_accompaniment[] = {{")
        for start, hz, units in events:
            begin = round(start * 60000 / (bpm * 4))
            end = round((start + units) * 60000 / (bpm * 4))
            duration = end - begin - (30 if hz else 0)
            assert 0 < duration <= 65535
            note = "NOTE_DO" if hz else "SONG_NOTE_REST"
            lines.append(f"    {{ {note}, OCT_MID, {duration}U, {hz}U }}, /* bar {start // 16 + 1} */")
        lines.append("};")
        audit_rows.extend((name,) + a for a in audit)
        preview.append((name, bpm, melody, events))
        print(f"{name}: {len(events)} accompaniment events, {round(sum(e[2] for e in events) * 60000 / (bpm * 4))}ms")
    (ROOT / "BSP/Audio/06_audio_song/song_accompaniment.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with (ROOT / "docs/song_accompaniment.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["song", "bar", "offset_16th", "notated_bass", "units_16th", "frequency_hz"])
        writer.writerows(audit_rows)
    return preview


def render_preview(preview, folder):
    import re
    import wave
    import numpy as np
    folder = Path(folder)
    folder.mkdir(exist_ok=True, parents=True)
    source = (ROOT / "BSP/Audio/03_audio_pwm/audio_pwm.c").read_text(encoding="utf-8")
    tables = []
    for name in ("s_wave_piano_bright", "s_wave_piano_mellow"):
        body = re.search(name + r"\[128\]\s*=\s*\{([^}]+)\}", source).group(1)
        tables.append(np.array([int(v) for v in re.findall(r"-?\d+", body)], dtype=np.float64))
        assert len(tables[-1]) == 128
    for name, bpm, melody, accompaniment in preview:
        rate = 32000
        samples = round(sum(e[2] for e in melody) * 60000 / (bpm * 4)) * rate // 1000
        mixed, amplitude = np.zeros(samples), np.zeros(samples)
        for track in (melody, accompaniment):
            for start, hz, units in track:
                if not hz:
                    continue
                begin = round(start * 60000 / (bpm * 4)) * rate // 1000
                end = (round((start + units) * 60000 / (bpm * 4)) - 30) * rate // 1000
                t = np.arange(end - begin) / rate * 1000
                env = np.select([t < 2, t < 182, t < 2182],
                                [t / 2, 1 - (t - 2) * 0.65 / 180,
                                 0.35 * (1 - (t - 182) / 2000)], default=0)
                mix = np.minimum(t / 400, 1)
                idx = (np.arange(end - begin) * hz / rate * 128).astype(np.int64) % 128
                mixed[begin:end] += (tables[0][idx] * (1 - mix) + tables[1][idx] * mix) * env
                amplitude[begin:end] += env
        # Same total-envelope normalization as the two-voice mixer, at ideal PC timing.
        pcm = (mixed / np.maximum(1, amplitude) * 180).astype(np.int16)
        dest = folder / f"{name}_双声部钢琴试听.wav"
        with wave.open(str(dest), "wb") as f:
            f.setnchannels(1)
            f.setsampwidth(2)
            f.setframerate(rate)
            f.writeframes(pcm.tobytes())
        print(f"PC piano preview: {dest}, {samples / rate:.3f}s")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview-dir", type=Path)
    args = parser.parse_args()
    preview = generate()
    if args.preview_dir:
        render_preview(preview, args.preview_dir)
