"""Pack cropped lion-dance video frames (ordered PNGs at 12.5 fps)."""
import argparse
from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageFilter

from import_c4 import fnv

ROOT = Path(__file__).resolve().parents[1]
W, H = 76, 96
X, Y = 26, 39
TOP, END = 30, 138
ROI = (172, 16, 464, 334)
HEADER = 12


def cutout(path):
    frame = Image.open(path).convert("RGB").crop(ROI)
    mask = Image.new("L", frame.size)
    mask.putdata([255 if min(rgb) < 225 else 0 for rgb in frame.getdata()])
    mask = mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
    ImageDraw.floodfill(mask, (0, 0), 128)
    mask = mask.point(lambda x: 0 if x == 128 else 255)
    frame.putalpha(mask)
    return frame


def c_array(name, ctype, data):
    lines = [f"static const {ctype} {name}[] = {{"]
    for i in range(0, len(data), 10):
        lines.append("    " + ", ".join(f"0x{x:X}U" for x in data[i:i + 10]) + ",")
    return "\n".join(lines + ["};", ""])


def pack(paths):
    cutouts = [cutout(path) for path in paths]
    boxes = [im.getbbox() for im in cutouts]
    bounds = (min(box[0] for box in boxes), min(box[1] for box in boxes),
              max(box[2] for box in boxes), max(box[3] for box in boxes))
    tiles = []
    for im in cutouts:
        im = im.crop(bounds)
        im.thumbnail((W, H - 2), Image.Resampling.LANCZOS)
        tile = Image.new("RGBA", (W, H))
        tile.paste(im, ((W - im.width) // 2, H - im.height))
        tiles.append(tile)

    rgb = [p[:3] for tile in tiles[::2] for p in tile.getdata() if p[3] >= 155]
    swatch = Image.new("RGB", (len(rgb), 1))
    swatch.putdata(rgb)
    palette = swatch.quantize(colors=255, dither=Image.Dither.NONE)
    colors = palette.getpalette()[:765]
    rgb565 = [0] + [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3
                    for r, g, b in zip(colors[::3], colors[1::3], colors[2::3])]
    frames = []
    for tile in tiles:
        q = tile.convert("RGB").quantize(palette=palette, dither=Image.Dither.NONE)
        frames.append([c + 1 if p[3] >= 155 else 0 for c, p in zip(q.getdata(), tile.getdata())])

    offsets, payload, max_span, total_pixels = [], bytearray(), 0, 0
    for i, frame in enumerate(frames):
        offsets.append(HEADER + len(payload))
        rows, runs = [0], bytearray()
        previous = frames[i - 1]
        damage = bytearray()
        for y in range(TOP, END, 2):
            changed = [x for x in range(W) if any(
                0 <= row < H and frame[row * W + x] != previous[row * W + x]
                for row in (y - Y, y + 1 - Y))]
            if changed:
                width = changed[-1] - changed[0] + 1
                damage.extend([X + changed[0], width])
                total_pixels += 2 * width
            else:
                damage.extend([0, 0])
        for y in range(H):
            row = frame[y * W:(y + 1) * W]
            x = 0
            while x < W:
                if row[x] == 0:
                    x += 1
                    continue
                start = x
                while x < W and row[x] != 0:
                    x += 1
                runs.extend([start, x - start, *row[start:x]])
            rows.append(len(runs))
        max_span = max(max_span, max(b - a for a, b in zip(rows, rows[2:])))
        payload.extend(struct.pack(f"<{len(rows)}H", *rows) + damage + runs)
    offsets.append(HEADER + len(payload))
    assert len(paths) < 256 and max_span <= 232 and offsets[-1] <= 0x100000
    header = struct.pack("<4sII", b"DSL1", len(payload), fnv(payload))
    text = "/* Generated by tools/gen_ds_lion.py. */\n"
    text += f"#define LION_WIDTH {W}U\n#define LION_HEIGHT {H}U\n"
    text += f"#define LION_X {X}U\n#define LION_Y {Y}U\n#define LION_FRAMES {len(paths)}U\n"
    text += c_array("s_lion_header", "uint8_t", header)
    text += c_array("s_lion_palette", "uint16_t", rgb565)
    text += c_array("s_lion_offsets", "uint32_t", offsets)
    (ROOT / "BSP/Src/ds_lion_art.inc").write_text(text, encoding="ascii")
    (ROOT / "assets/ds_room_lion.bin").write_bytes(header + payload)
    print(f"Lion: {len(paths)} frames, {offsets[-1]} bytes, max {max_span} bytes/strip, "
          f"{total_pixels // len(paths)} changed pixels/frame average")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("frames", type=Path)
    args = parser.parse_args()
    pack(sorted(args.frames.glob("*.png")))
