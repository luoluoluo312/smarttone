"""Generate the three SmartTone bitmap fonts.

12x12 4bpp body, 16x16 4bpp titles, 24x24 1bpp numeric/note glyphs.
All tables are const and live in Flash; no runtime allocation.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = Path(r"C:\Windows\Fonts\simhei.ttf")
OUT_C = ROOT / "BSP" / "Src" / "font.c"
OUT_H = ROOT / "BSP" / "Inc" / "font.h"

ALL_CHARS = "跳舞弹琴返小屋自动作新建叠关闭无乐入大就戏按旋束游结绪进速钮长加主菜单演奏音区设置移调节拍器曲库系统状态开启号量目列表回放播中已暂停事件亮度色录待机满保存失败"
TITLE_CHARS = "叠加主菜单演奏音区设置移调节拍器曲目列表回放系统录音"
NUM_CHARS = "0123456789+-DOC:播放中已暂停"


def mask(ch: str, size: int) -> Image.Image:
    font = ImageFont.truetype(str(FONT_PATH), size)
    canvas = Image.new("L", (size * 3, size * 3), 0)
    ImageDraw.Draw(canvas).text(
        (canvas.width // 2, canvas.height // 2), ch, font=font, fill=255, anchor="mm"
    )
    box = canvas.getbbox()
    if box is None:
        raise RuntimeError(f"no ink for {ch}")
    glyph = canvas.crop(box)
    if glyph.width > size or glyph.height > size:
        raise RuntimeError(f"{ch} {glyph.size} > {size}")
    cell = Image.new("L", (size, size), 0)
    cell.paste(glyph, ((size - glyph.width) // 2, (size - glyph.height) // 2))
    return cell


def nibble_data(mask_img: Image.Image) -> bytes:
    values = []
    for y in range(mask_img.height):
        for x in range(mask_img.width):
            values.append(round(mask_img.getpixel((x, y)) * 15 / 255))
    out = bytearray()
    for i in range(0, len(values), 2):
        hi = values[i]
        lo = values[i + 1] if i + 1 < len(values) else 0
        out.append((hi << 4) | lo)
    return bytes(out)


def one_bit_data(mask_img: Image.Image) -> bytes:
    out = bytearray()
    for y in range(mask_img.height):
        value = 0
        bits = 0
        for x in range(mask_img.width):
            value = (value << 1) | (1 if mask_img.getpixel((x, y)) >= 128 else 0)
            bits += 1
            if bits == 8:
                out.append(value)
                value = 0
                bits = 0
        if bits:
            value <<= 8 - bits
            out.append(value)
    return bytes(out)


def emit_font(lines: list[str], name: str, chars: str, size: int,
              bpp: int, gap: int) -> None:
    chars = "".join(dict.fromkeys(chars))
    bytes_per = (size * size * bpp + 7) // 8
    lines.append(f"/* {name}: {size}x{size}, {bpp} bpp, {len(chars)} glyphs */")
    for ch in chars:
        data = one_bit_data(mask(ch, size)) if bpp == 1 else nibble_data(mask(ch, size))
        lines.append(f"static const uint8_t {name}_{ord(ch):04x}[{bytes_per}] = {{")
        for i in range(0, len(data), 12):
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 12]) + ",")
        lines.append("};")
        lines.append("")
    lines.append(f"static const font_glyph_t {name}_glyphs[] = {{")
    for ch in chars:
        lines.append(f"    {{0x{ord(ch):04X}u, {name}_{ord(ch):04x}}}, /* {ch} */")
    lines += [
        "};",
        "",
        f"const font_t {name} = {{",
        f"    {size}U, {size}U, {bpp}U, {gap}U, {bytes_per}U,",
        f"    {name}_glyphs,",
        f"    (uint16_t)(sizeof({name}_glyphs) / sizeof({name}_glyphs[0]))",
        "};",
        "",
    ]


def main() -> None:
    missing = [c for c in TITLE_CHARS if c not in ALL_CHARS]
    if missing:
        raise RuntimeError(f"title chars missing from body: {missing}")

    OUT_H.write_text(
        """#ifndef FONT_H
#define FONT_H

#include <stdint.h>

typedef struct {
    uint32_t codepoint;
    const uint8_t *data;
} font_glyph_t;

typedef struct {
    uint8_t width;
    uint8_t height;
    uint8_t bpp;
    uint8_t gap;
    uint16_t bytes_per_glyph;
    const font_glyph_t *glyphs;
    uint16_t count;
} font_t;

extern const font_t font12;
extern const font_t font16;
extern const font_t font24;

#endif
""",
        encoding="utf-8",
    )

    lines = [
        "/* Auto-generated by tools/gen_fonts_advanced.py. Do not edit. */",
        '#include "font.h"',
        "",
    ]
    emit_font(lines, "font12", ALL_CHARS, 12, 4, 0)
    emit_font(lines, "font16", TITLE_CHARS, 16, 4, 0)
    emit_font(lines, "font24", NUM_CHARS, 24, 1, 0)
    OUT_C.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT_C, OUT_C.stat().st_size, "bytes")
    print("fonts", len(ALL_CHARS), len(TITLE_CHARS), len(NUM_CHARS))


if __name__ == "__main__":
    main()
