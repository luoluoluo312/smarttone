"""Transcribe the user-supplied three-page C-major score, upper voice only.

Token: degree[ h=C5 / x=C6 ]:sixteenth-units. Bare degrees use C4.
Prefix ~ joins the preceding identical pitch without a new attack.
Full bars have 16 units; a 3-beat tied ending stops before the interlude.
Trill at bar 8 is omitted. No left-hand accompaniment is included.
"""
from pathlib import Path
import csv

ROOT = Path(__file__).resolve().parent.parent
BPM = 80  # Score has no tempo marking; chosen explicitly for this arrangement.
# Page 1, seven systems of four bars.
BARS = [
    "0:4 0:2 5x:1 6x:1 5x:2 3x:2 2x:2 3x:2",
    "2x:2 1x:2 6h:8 2x:2 3x:2",
    "2x:2 1x:2 5h:8 2x:2 3x:2",
    "2x:2 1x:2 6h:4 1x:2 2x:4 6h:2",
    "3x:8 1x:2 2x:2 3x:2 5x:2",
    "5x:2 3x:2 3x:4 2x:4 1x:4",
    "2x:2 1x:2 6h:4 1x:2 2x:2 3x:4",
    "5x:16",
    "0:4 0:4 0:2 2h:2 1h:2 6:2",
    "1h:4 1h:2 6:2 1h:4 1h:2 6:2",
    "1h:2 6:2 5:4 0:2 2h:2 1h:2 6:2",
    "1h:4 1h:2 6:2 1h:4 1h:2 3h:2",
    "2h:2 1h:2 1h:4 0:2 5:2 6:2 3h:2",
    "3h:4 3h:2 2h:2 3h:4 3h:2 2h:2",
    "3h:2 5h:2 3h:2 0:2 3h:2 3h:2 3h:4",
    "2h:2 2h:2 2h:2 2h:2 2h:4 1h:2 3h:2",
    "~3h:2 2h:6 0:2 2h:2 1h:2 6:2",
    "1h:4 1h:2 6:2 1h:4 1h:2 6:2",
    "1h:2 6:2 5:4 0:2 5:2 6:2 3h:2",
    "5h:4 5h:2 3h:2 5h:4 5h:2 3h:2",
    "2h:2 1h:2 1h:4 0:2 2h:2 1h:2 2h:2",
    "3h:2 2h:2 2h:2 1h:2 2h:4 1h:2 6:2",
    "2h:2 1h:2 1h:2 6:2 1h:4 1h:2 1h:2",
    "~1h:16",
    "0:4 0:4 0:2 5h:2 5h:2 3h:2",
    "2h:2 3h:2 6:4 2h:2 3h:2 5h:2 3h:2",
    "2h:8 0:2 5h:2 5h:2 3h:2",
    "2h:2 3h:2 5:4 2h:2 3h:2 5h:2 2h:2",
    # Page 2, systems 1..3: complete first chorus, then its tied ending.
    "1h:8 0:2 1h:2 2h:2 3h:2",
    "5h:2 6h:2 5h:2 3h:2 5h:2 3h:2 3h:2 2h:2",
    "2h:8 0:2 1h:2 2h:2 1h:2",
    "2h:4 1h:2 2h:2 ~2h:2 3h:2 5h:4",
    "3h:2 3h:6 0:2 5h:2 5h:2 3h:2",
    "2h:2 3h:2 6:4 2h:2 3h:2 5h:2 3h:2",
    "2h:8 0:2 5h:2 5h:2 3h:2",
    "2h:2 3h:2 5:4 2h:2 3h:2 5h:2 2h:2",
    "1h:8 0:2 1h:2 2h:2 3h:2",
    "5h:2 6h:2 5h:2 3h:2 5h:2 3h:2 3h:2 2h:2",
    "2h:4 0:2 5:2 3h:4 2h:2 2h:2",
    "~2h:2 1h:6 ~1h:8",
    "~1h:12",  # Stop on the held final syllable, before interlude pickup 3/5.
]



def transcribe():
    assert len(BARS) == 41
    rows, events = [], []
    cursor = 0
    semitones = [0, 2, 4, 5, 7, 9, 11]
    for bar, text in enumerate(BARS, 1):
        assert sum(int(t.split(":")[1]) for t in text.split()) == (12 if bar == 41 else 16), (bar, text)
        offset = 0
        for token in text.split():
            pitch, length = token.split(":")
            length = int(length)
            tied = pitch.startswith("~")
            pitch = pitch.lstrip("~")
            octave = 6 if pitch.endswith("x") else (5 if pitch.endswith("h") else 4)
            degree = int(pitch[0])
            midi = None if degree == 0 else 12 * (octave + 1) + semitones[degree - 1]
            hz = 0 if midi is None else round(440 * 2 ** ((midi - 69) / 12))
            rows.append((bar, (bar - 1) // 4 + 1, offset, degree, octave if degree else 0, length, int(tied), hz))
            if tied:
                assert events and events[-1][1] == hz and hz != 0, (bar, token)
                events[-1][2] += length
            else:
                events.append([cursor, hz, length])
            cursor += length
            offset += length
    assert cursor == 40 * 16 + 12
    return rows, events


def generate():
    rows, events = transcribe()
    dest = ROOT / "BSP/Audio/06_audio_song/song_qinghuaci.inc"
    lines = ["/* Generated by tools/gen_qinghuaci.py from the supplied 3-page score.",
             " * C major, 80 BPM, first chorus ending at bar 41 beat 3; melody only.",
             " * The 30ms built-in articulation gap is included in each grid slot.",
             " * Fixed frequencies preserve G4..A6 regardless of keyboard settings. */",
             "static const SongNote s_qinghuaci[] = {"]
    for start, hz, units in events:
        start_ms = round(start * 60000 / (BPM * 4))
        end_ms = round((start + units) * 60000 / (BPM * 4))
        duration = end_ms - start_ms - (30 if hz else 0)
        assert 0 < duration <= 65535
        note = "SONG_NOTE_REST" if hz == 0 else "NOTE_DO"
        lines.append(f"    {{ {note}, OCT_MID, {duration}U, {hz}U }}, /* bar {start // 16 + 1}, unit {start % 16} */")
    lines += ["};", ""]
    dest.write_text("\n".join(lines), encoding="utf-8")
    audit = ROOT / "docs/qinghuaci_score.csv"
    audit.parent.mkdir(exist_ok=True)
    with audit.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["bar", "system", "offset_16th", "degree", "octave", "units_16th", "tie", "frequency_hz"])
        w.writerows(rows)
    print(f"Qing Hua Ci: {len(BARS)} bars, {len(events)} events, {(40 * 16 + 12) * 60000 // (BPM * 4)}ms; {dest}")
    return events


if __name__ == "__main__":
    events = generate()
    import sys
    if "--preview" in sys.argv:
        import re
        import wave
        import numpy as np
        dest = Path(sys.argv[sys.argv.index("--preview") + 1])
        pwm = (ROOT / "BSP/Audio/03_audio_pwm/audio_pwm.c").read_text(encoding="utf-8")
        tables = []
        for name in ("s_wave_piano_bright", "s_wave_piano_mellow"):
            body = re.search(name + r"\[128\]\s*=\s*\{([^}]+)\}", pwm).group(1)
            table = np.array([int(v) for v in re.findall(r"-?\d+", body)], dtype=np.float64)
            assert len(table) == 128
            tables.append(table)
        rate = 32000
        total_units = sum(e[2] for e in events)
        total_samples = round(total_units * 60 / (BPM * 4) * rate)
        pcm = np.zeros(total_samples, dtype=np.int16)
        for start, hz, units in events:
            if not hz:
                continue
            begin_ms = round(start * 60000 / (BPM * 4))
            end_ms = round((start + units) * 60000 / (BPM * 4)) - 30
            begin, end = begin_ms * rate // 1000, end_ms * rate // 1000
            t = np.arange(end - begin) / rate * 1000
            env = np.select([t < 2, t < 182, t < 2182],
                            [t / 2, 1 - (t - 2) * 0.65 / 180,
                             0.35 * (1 - (t - 182) / 2000)], default=0)
            mix = np.minimum(t / 400, 1)
            # Same two piano tables and envelope as firmware; ideal PC clock.
            idx = (np.arange(end - begin) * hz / rate * 128).astype(np.int64) % 128
            values = (tables[0][idx] * (1 - mix) + tables[1][idx] * mix) * env * 180
            pcm[begin:end] = values.astype(np.int16)
        with wave.open(str(dest), "wb") as f:
            f.setnchannels(1)
            f.setsampwidth(2)
            f.setframerate(rate)
            f.writeframes(pcm.tobytes())
        print(f"PC piano preview: {dest}, {len(pcm) / rate:.2f}s")
