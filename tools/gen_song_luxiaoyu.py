def parse(text):
    return [(word.split(':')[0], Fraction(word.split(':')[1]) if ':' in word
             else Fraction(1, 4)) for word in text.split()]


def frequency(pitch):
    if pitch == 'R':
        return 0
    degree = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}[pitch[0]]
    accidental = (1 if '#' in pitch else -1 if 'b' in pitch else 0)
    midi = (int(pitch[-1]) + 1) * 12 + degree + accidental
    return math.floor(440 * 2 ** ((midi - 69) / 12) + 0.5)


def render(name, bars):
    lines = [f'static const SongNote {name}[] = {{']
    elapsed = Fraction(0)
    events = []
    for bar in order:
        notes = parse(bars[bar])
        assert sum(length for _, length in notes) == 4, bar
        for pitch, length in notes:
            start = round(elapsed)
            elapsed += length * Fraction(60000, 55 if bar >= 49 else 70)
            duration = round(elapsed) - start
            hz = frequency(pitch)
            assert duration > 0 and (hz == 0 or 65 <= hz <= 4000)
            # Merge the tied final chord across bars 49/50; no reattack.
            if bar == 50:
                old_hz, old_dur, old_bar = events.pop()
                assert old_hz == hz
                events.append((hz, old_dur + duration, old_bar))
            else:
                events.append((hz, duration, bar))
    for hz, duration, bar in events:
        note = 'NOTE_DO' if hz else 'SONG_NOTE_REST'
        # The player adds a 30 ms articulation gap to every sounding event.
        if hz:
            duration -= 30
        assert duration > 0
        lines.append(f'    {{ {note}, OCT_MID, {duration}U, {hz}U }}, /* score bar {bar} */')
    lines.append('};')
    print(name, len(events), 'events,', round(elapsed), 'ms')
    return '\n'.join(lines)


