"""Pack the DS room's transparent character poses and expression tiles for TFT."""
from pathlib import Path
import struct

from import_c4 import fnv
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
assets = ROOT / "assets"
sprite = Image.open(assets / "ds_room_sprite.png").convert("RGBA")
dance = Image.open(assets / "ds_room_dance.png").convert("RGBA")
assert sprite.size == (86, 109) and dance.size == (228, 96)


def expression(happy):
    # Keep the original mouth and replace only the irises and lids.
    tile = Image.new("RGBA", (35 * 4, 16 * 4))
    draw = ImageDraw.Draw(tile)

    def points(coords):
        return [((x - 25) * 4, (y - 40) * 4) for x, y in coords]

    for x in (32, 50):
        draw.polygon(points([(x-5, 44), (x-3, 42), (x+2, 42), (x+6, 44),
                             (x+6, 48), (x+4, 50), (x-3, 50), (x-5, 48)]),
                     fill="#f9dcd2")
        if happy:
            lid = [(x-5, 47), (x-3, 45.5), (x, 45), (x+2, 45.3), (x+5, 47)]
        else:
            lid = [(x-5, 46.5), (x-3, 47.7), (x, 48), (x+3, 47.7), (x+5, 46.5)]
        draw.line(points(lid), fill="#352235", width=5, joint="curve")
        if happy:
            cheek_x = x - 6 if x == 32 else x + 3
            draw.ellipse(points([(cheek_x, 50), (cheek_x + 3, 51.5)]), fill="#f2a9a6")
    return tile.resize((35, 16), Image.Resampling.LANCZOS)


def array(ctype, name, values):
    step = 16 if ctype == "uint8_t" else 12
    rows = ["    " + ", ".join(f"0x{n:02X}U" for n in values[i:i + step]) + ","
            for i in range(0, len(values), step)]
    return f"static const {ctype} {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


images = [("s_sprite", sprite), ("s_blink", expression(False)), ("s_smile", expression(True))]
images += [(f"s_dance_{i}", dance.crop((i * 76, 0, (i + 1) * 76, 96))) for i in range(3)]
# Shared colors are learned together. Index 0 in the firmware asset is transparent.
opaque = [(r, g, b) for _, im in images for r, g, b, a in im.getdata() if a >= 150]
swatch = Image.new("RGB", (len(opaque), 1))
swatch.putdata(opaque)
palette = swatch.quantize(colors=255, dither=Image.Dither.NONE)
rgb = palette.getpalette()
rgb565 = [0] + [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3
               for r, g, b in zip(rgb[0:765:3], rgb[1:765:3], rgb[2:765:3])]
output = "/* Generated by tools/gen_ds_room.py. Transparent pixels are omitted from row runs. */\n"
output += array("uint16_t", "s_ds_palette", rgb565)
payload = bytearray()
HEADER_SIZE = 12
dance_pixels = []
for name, im in images:
    indexed = im.convert("RGB").quantize(palette=palette, dither=Image.Dither.NONE)
    values = [idx + 1 if a >= 150 else 0 for idx, (_, _, _, a) in zip(indexed.getdata(), im.getdata())]
    assert max(values) <= 255
    offsets = [0]
    runs = []
    for y in range(im.height):
        row = values[y * im.width:(y + 1) * im.width]
        x = 0
        while x < len(row):
            if row[x] == 0:
                x += 1
                continue
            start = x
            while x < len(row) and row[x] != 0:
                x += 1
            runs.extend([start, x - start])
            runs.extend(row[start:x])
        offsets.append(len(runs))
    output += array("uint16_t", name + "_rows", offsets)
    if name.startswith("s_dance_"):
        # Any pair of rows fits in the firmware's two-row read buffer.
        assert max(b - a for a, b in zip(offsets, offsets[2:])) <= 232
        loc = f"{HEADER_SIZE + len(payload)}U"
        payload.extend(runs)
        dance_pixels.append(values)
        output += f"static const ds_sprite_t {name} = {{ {name}_rows, NULL, {loc} }};\n"
    else:
        output += array("uint8_t", name + "_runs", runs)
        output += f"static const ds_sprite_t {name} = {{ {name}_rows, {name}_runs, 0U }};\n"
# (pose, center x, lift, rendered width, mirror). Extra frames ease into and
# out of the turn and give each hop an ascent, apex, and landing.
steps = [
    (0, 59, 0, 76, False), (0, 57, 2, 76, False),
    (0, 55, 4, 76, False), (0, 54, 5, 76, False),
    (0, 55, 4, 76, False), (0, 57, 2, 73, False),
    (0, 59, 2, 56, False), (1, 61, 3, 58, False),
    (1, 63, 4, 74, False), (1, 65, 3, 76, False),
    (1, 66, 2, 60, False), (0, 68, 3, 58, True),
    (0, 68, 2, 73, True), (0, 67, 0, 76, True),
    (2, 66, 1, 76, False), (2, 65, 4, 76, False),
    (2, 64, 6, 76, False), (2, 63, 5, 76, False),
    (2, 62, 2, 76, False), (2, 61, 0, 76, False),
    (2, 60, 2, 76, False), (2, 59, 5, 76, False),
    (2, 58, 6, 76, False), (2, 57, 4, 76, False),
    (2, 57, 1, 76, False), (2, 58, 0, 76, False),
]
DANCE_TOP, DANCE_BOTTOM = 30, 138


def dance_frame(step):
    pose, center, lift, width, mirror = step
    x, y = center - width // 2, 39 - lift
    frame = [[0] * 128 for _ in range(160)]
    # Keep the shadow distinct from all sprite palette indices.
    for row in frame[133:137]:
        row[center - 17:center + 18] = [256] * 35
    for cy in range(96):
        for cx in range(width):
            src = cx * 76 // width
            if mirror:
                src = 75 - src
            color = dance_pixels[pose][cy * 76 + src]
            if color:
                frame[y + cy][x + cx] = color
    return frame


frames = [dance_frame(step) for step in steps]
damage = []
for i, frame in enumerate(frames):
    old = frames[i - 1]
    for y in range(DANCE_TOP, DANCE_BOTTOM, 2):
        changed = [x for x in range(128) if any(
            frame[row][x] != old[row][x] for row in (y, y + 1))]
        damage.extend([min(changed), max(changed) - min(changed) + 1] if changed else [0, 0])
output += f"#define DANCE_Y {DANCE_TOP}U\n#define DANCE_END {DANCE_BOTTOM}U\n"
output += "static const ds_step_t s_steps[] = {\n"
for pose, center, lift, width, mirror in steps:
    output += f"    {{ &s_dance_{pose}, {center}U, {lift}U, {width}U, {str(mirror).lower()} }},\n"
output += "};\n"
output += array("uint8_t", "s_dance_damage", damage)
header = struct.pack("<4sII", b"DSD1", len(payload), fnv(payload))
assert len(header) + len(payload) <= 0x8000
output += array("uint8_t", "s_ds_dance_header", header)
output += f"#define DS_DANCE_ASSET_BYTES {len(header) + len(payload)}U\n"
output += f"#define DS_DANCE_FNV 0x{fnv(payload):08X}UL\n"
(assets / "ds_room_dance.bin").write_bytes(header + payload)
(ROOT / "BSP/Src/ds_room_art.inc").write_text(output, encoding="ascii")
