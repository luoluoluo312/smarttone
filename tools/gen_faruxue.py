"""Fa Ru Xue: supplied B-major score, intro through first chorus only.

58 BPM; unmarked degree 1 = B3, h = one octave up, l = one octave down.
Token degree:duration uses sixteenth-note units; ~ is a same-pitch tie.
22 complete 4/4 bars + first two beats of bar 23, ending on the held "bei".
The following X-marked rap, repeat instructions and page-2 coda are excluded.
"""
from pathlib import Path
import csv

ROOT = Path(__file__).resolve().parent.parent
BPM = 58
BARS = [
    "0:2 5:1 6:1 1h:2 3h:2 2h:3 3h:1 2h:2 1h:2",
    "0:2 5:1 6:1 1h:2 3h:2 2h:3 5h:1 3h:2 1h:2",
    "2:2 3:1 3:1 ~3:4 2:2 3:1 5:1 ~5:1 3:2 1:1",
    "2:2 3:1 3:1 ~3:4 2:2 3:1 6:1 ~6:1 5:2 3:1",
    "~3:1 2:1 1:2 0:3 6l:1 1:2 2:1 2:1 ~2:1 6l:2 1:1",
    "~1:1 2:3 0:3 1:1 1:2 2:1 3:1 ~3:1 2:3",
    "2:2 3:1 3:1 ~3:4 2:2 3:1 5:1 ~5:1 3:2 1:1",
    "2:2 3:1 3:1 ~3:3 3:1 2:2 3:1 6:1 ~6:1 5:2 3:1",
    "~3:1 2:1 1:2 0:3 6l:1 1:2 2:1 2:1 ~2:1 6l:2 1:1",
    "~1:2 2:1 2:1 ~2:4 1:2 2:1 3:1 ~3:1 2:2 1:1",
    "~1:4 6l:1 1:1 6l:1 1:1 ~1:1 6l:2 1:1 ~1:1 2:2 1:1",
    "~1:4 6l:1 1:1 6l:1 1:1 ~1:1 6l:2 1:1 ~1:1 1:1 3:2",
    "1:4 3:2 3:2 3:2 6:2 5:2 3:1 3:1",
    "~3:1 2:3 ~2:4 0:2 5l:2 2:2 3:1 3:1",
    "3:2 2:1 3:1 ~3:2 5:1 6:1 ~6:1 5:3 1:2 2:2",
    "3:2 6:2 5:2 3:1 5:1 ~5:4 0:2 5:1 6:1",
    "1h:3 6:1 6:2 5:2 3:2 5:1 3:1 ~3:2 1:1 2:1",
    "3:2 1:1 6l:1 ~6l:1 3:1 2:2 ~2:3 5l:1 2:2 3:1 3:1",
    "3:2 2:1 3:1 ~3:2 5:1 6:1 ~6:1 5:3 1:2 2:2",
    "3:2 6:2 5:2 3:1 5:1 ~5:4 0:2 5:1 6:1",
    "1h:3 6:1 6:2 5:2 3:2 5:1 3:1 ~3:3 1:1",
    "6l:2 3:1 2:1 ~2:3 1:1 1:2 6l:2 1:2 2:1 2:1",
    "~2:2 1:2 ~1:4",
]


def transcribe():
    assert len(BARS) == 23
    rows, events = [], []
    cursor = 0
    degrees = [0, 2, 4, 5, 7, 9, 11]
    for bar, text in enumerate(BARS, 1):
        assert sum(int(t.split(":")[1]) for t in text.split()) == (8 if bar == 23 else 16), bar
        offset = 0
        for token in text.split():
            pitch, units = token.split(":")
            units = int(units)
            tied = pitch.startswith("~")
            pitch = pitch.lstrip("~")
            octave = 4 if pitch.endswith("h") else (2 if pitch.endswith("l") else 3)
            degree = int(pitch[0])
            midi = 12 * (octave + 1) + 11 + degrees[degree - 1] if degree else None
            hz = round(440 * 2 ** ((midi - 69) / 12)) if midi is not None else 0
            rows.append((bar, offset, degree, octave if degree else 0, units, int(tied), hz))
            if tied:
                assert events and events[-1][1] == hz and hz != 0, (bar, token)
                events[-1][2] += units
            else:
                events.append([cursor, hz, units])
            cursor += units
            offset += units
    assert cursor == 360
    return rows, events


def generate():
    rows, events = transcribe()
    lines = ["/* Generated by tools/gen_faruxue.py from the supplied score.",
             " * B major, 58 BPM, degree 1 = B3. Intro through first chorus.",
             " * 22 bars + 2 beats. Ties merged; rap/repeats/coda excluded.",
             " * Each grid slot includes the existing 30ms articulation gap. */",
             "static const SongNote s_faruxue[] = {"]
    for start, hz, units in events:
        begin = round(start * 60000 / (BPM * 4))
        end = round((start + units) * 60000 / (BPM * 4))
        duration = end - begin - (30 if hz else 0)
        assert 0 < duration <= 65535
        note = "NOTE_DO" if hz else "SONG_NOTE_REST"
        lines.append(f"    {{ {note}, OCT_MID, {duration}U, {hz}U }}, /* bar {start // 16 + 1}, unit {start % 16} */")
    lines += ["};", ""]
    (ROOT / "BSP/Audio/06_audio_song/song_faruxue.inc").write_text("\n".join(lines), encoding="utf-8")
    with (ROOT / "docs/faruxue_score.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["bar", "offset_16th", "degree", "tonic_octave", "units_16th", "tie", "frequency_hz"])
        writer.writerows(rows)
    print(f"Fa Ru Xue: {len(events)} events, {round(360 * 60000 / (BPM * 4))}ms")
    return events


if __name__ == "__main__":
    events = generate()
    import sys
    if "--preview" in sys.argv:
        import re
        import wave
        import numpy as np
        dest = Path(sys.argv[sys.argv.index("--preview") + 1])
        pwm = (ROOT / "BSP/Audio/03_audio_pwm/audio_pwm.c").read_text(encoding="utf-8")
        tables = []
        for name in ("s_wave_piano_bright", "s_wave_piano_mellow"):
            body = re.search(name + r"\[128\]\s*=\s*\{([^}]+)\}", pwm).group(1)
            table = np.array([int(v) for v in re.findall(r"-?\d+", body)], dtype=np.float64)
            assert len(table) == 128
            tables.append(table)
        rate = 32000
        total_units = sum(e[2] for e in events)
        total_samples = round(total_units * 60 / (BPM * 4) * rate)
        pcm = np.zeros(total_samples, dtype=np.int16)
        for start, hz, units in events:
            if not hz:
                continue
            begin_ms = round(start * 60000 / (BPM * 4))
            end_ms = round((start + units) * 60000 / (BPM * 4)) - 30
            begin, end = begin_ms * rate // 1000, end_ms * rate // 1000
            t = np.arange(end - begin) / rate * 1000
            env = np.select([t < 2, t < 182, t < 2182],
                            [t / 2, 1 - (t - 2) * 0.65 / 180,
                             0.35 * (1 - (t - 182) / 2000)], default=0)
            mix = np.minimum(t / 400, 1)
            # Same two piano tables and envelope as firmware; ideal PC clock.
            idx = (np.arange(end - begin) * hz / rate * 128).astype(np.int64) % 128
            values = (tables[0][idx] * (1 - mix) + tables[1][idx] * mix) * env * 180
            pcm[begin:end] = values.astype(np.int16)
        with wave.open(str(dest), "wb") as f:
            f.setnchannels(1)
            f.setsampwidth(2)
            f.setframerate(rate)
            f.writeframes(pcm.tobytes())
        print(f"PC piano preview: {dest}, {len(pcm) / rate:.2f}s")
