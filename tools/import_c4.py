"""Convert the supplied recording to the fixed 16 kHz mono PCM asset format."""
import argparse
from array import array
import hashlib
import json
from pathlib import Path
import struct
import subprocess


def fnv(data):
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xFFFFFFFF
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--ffmpeg", required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    decoded = subprocess.run([args.ffmpeg, "-v", "error", "-i", str(args.source),
                          "-map", "0:a:0", "-ac", "1", "-ar", "16000",
                          "-f", "f32le", "pipe:1"],
                         check=True, stdout=subprocess.PIPE).stdout
    samples = array("f")
    samples.frombytes(decoded)
    # One fixed gain preserves dynamics and leaves 10% peak headroom.
    peak = max((abs(value) for value in samples), default=0)
    gain = 0.9 / peak if peak else 1.0
    pcm = bytes(max(0, min(255, round(128 + value * gain * 127))) for value in samples)
    if not pcm or len(pcm) + 32 > 0x100000:
        raise SystemExit("Recording does not fit the 1 MiB sample partition")
    checksum = fnv(pcm)
    header = struct.pack("<4I16x", 0x314D4350, 16000, len(pcm), checksum)
    dest = root / "assets"
    dest.mkdir(exist_ok=True)
    (dest / "c4.pcm.bin").write_bytes(header + pcm)
    meta = {"source": args.source.name,
            "source_sha256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
            "asset_sha256": hashlib.sha256(header + pcm).hexdigest(),
            "format": "unsigned PCM8, mono, 16000 Hz", "address": "0x100000",
            "samples": len(pcm), "duration_ms": (len(pcm) + 15) // 16,
            "normalization_gain": gain,
            "fnv1a": f"{checksum:08x}"}
    (dest / "c4.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
                                 encoding="utf-8")
    include = root / "BSP/Audio/06_audio_song/song_c4_sample.inc"
    include.write_text("/* Generated by tools/import_c4.py; external W25Q64 asset. */\n"
                       "static const SampleDef s_c4_sample = {\n"
                       f"    0x100000UL, {len(pcm)}UL, 0x{checksum:08X}UL\n"
                       "};\n", encoding="utf-8")
    print(json.dumps(meta, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
